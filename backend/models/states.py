"""Application state machine (design doc section 4)."""
from __future__ import annotations

from enum import StrEnum


class Status(StrEnum):
    DISCOVERED = "DISCOVERED"
    SHORTLISTED = "SHORTLISTED"
    EXCLUDED = "EXCLUDED"
    RESUME_READY = "RESUME_READY"
    APPLICATION_PREPARED = "APPLICATION_PREPARED"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    CHANGES_REQUESTED = "CHANGES_REQUESTED"
    CANCELLED = "CANCELLED"
    INVALIDATED = "INVALIDATED"
    SUBMITTING = "SUBMITTING"
    SUBMITTED = "SUBMITTED"
    SUBMISSION_UNKNOWN = "SUBMISSION_UNKNOWN"
    MANUAL_VERIFICATION = "MANUAL_VERIFICATION"
    FAILED = "FAILED"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    INTERVIEW = "INTERVIEW"
    REJECTED = "REJECTED"
    OFFER = "OFFER"
    WITHDRAWN = "WITHDRAWN"


S = Status

TRANSITIONS: dict[Status, set[Status]] = {
    S.DISCOVERED: {S.SHORTLISTED, S.EXCLUDED, S.REVIEW_REQUIRED},
    S.SHORTLISTED: {S.RESUME_READY, S.REVIEW_REQUIRED, S.EXCLUDED},
    S.EXCLUDED: {S.SHORTLISTED},  # user override
    S.RESUME_READY: {S.APPLICATION_PREPARED, S.REVIEW_REQUIRED},
    S.APPLICATION_PREPARED: {S.AWAITING_APPROVAL, S.FAILED, S.REVIEW_REQUIRED},
    S.AWAITING_APPROVAL: {S.APPROVED, S.CHANGES_REQUESTED, S.CANCELLED},
    S.APPROVED: {S.SUBMITTING, S.INVALIDATED, S.CANCELLED},
    S.CHANGES_REQUESTED: {S.RESUME_READY, S.APPLICATION_PREPARED, S.REVIEW_REQUIRED, S.CANCELLED},
    S.INVALIDATED: {S.APPLICATION_PREPARED, S.AWAITING_APPROVAL, S.CANCELLED},
    S.SUBMITTING: {S.SUBMITTED, S.SUBMISSION_UNKNOWN, S.FAILED},
    S.SUBMISSION_UNKNOWN: {S.MANUAL_VERIFICATION},
    S.MANUAL_VERIFICATION: {S.SUBMITTED, S.FAILED},
    S.FAILED: {S.APPLICATION_PREPARED, S.REVIEW_REQUIRED, S.CANCELLED},
    S.SUBMITTED: {S.INTERVIEW, S.REJECTED, S.OFFER, S.WITHDRAWN},
    S.INTERVIEW: {S.REJECTED, S.OFFER, S.WITHDRAWN},
    S.OFFER: {S.WITHDRAWN},
    S.REJECTED: set(),
    S.WITHDRAWN: set(),
    S.CANCELLED: set(),
    # REVIEW_REQUIRED returns to an appropriate prior state; see allowed_next().
    S.REVIEW_REQUIRED: {S.SHORTLISTED, S.EXCLUDED, S.RESUME_READY, S.APPLICATION_PREPARED, S.CANCELLED},
}

# States in which an application is considered submitted (or possibly submitted):
# a new submission attempt must never start from these.
SUBMITTED_LIKE = {S.SUBMITTING, S.SUBMITTED, S.SUBMISSION_UNKNOWN, S.MANUAL_VERIFICATION,
                  S.INTERVIEW, S.OFFER, S.REJECTED, S.WITHDRAWN}

# Statuses that may only be entered through the approval gate, never via a generic transition.
GATED = {S.APPROVED, S.SUBMITTING, S.SUBMITTED}


def allowed_next(current: Status, previous: Status | None = None) -> set[Status]:
    allowed = set(TRANSITIONS[current])
    if current == S.REVIEW_REQUIRED and previous is not None and previous not in GATED:
        allowed.add(previous)
    return allowed
